const withButtons: SectionType[] = [
  "header",
  "homeHero",
  "hero",
  "usp",
  "guarantee",
  "cta",
  "contact",
  "footer",
];

const appearanceDefaults: Settings = {
  ...Object.fromEntries([...appearanceFields, ...buttonFields].map((f) => [f.key, ""])),
  paddingTop: 0,
  paddingBottom: 0,
};

for (const def of Object.values(sectionDefinitions)) {
  const extra = [
    ...appearanceFields,
    ...(withButtons.includes(def.type) ? buttonFields : []),
    ...spacingFields,
  ];
  const existing = new Set(def.schema.map((field) => field.key));
  def.schema = [...def.schema, ...extra.filter((field) => !existing.has(field.key))];
  def.defaults = {
    ...Object.fromEntries(
      Object.entries(appearanceDefaults).filter(([key]) => !(key in def.defaults)),
    ),
    ...def.defaults,
  };
}

