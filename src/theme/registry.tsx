const textList = (key: string, label: string, withIcon = false): Field => ({
  key,
  label,
  type: "list",
  itemFields: withIcon
    ? [
        { key: "text", label: "Texte", type: "text" },
        { key: "icon", label: "Icône", type: "icon" },
      ]
    : [{ key: "text", label: "Texte", type: "text" }],
  itemLabelKey: "text",
});

